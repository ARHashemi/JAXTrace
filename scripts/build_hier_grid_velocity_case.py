"""
build_hier_grid_velocity_case.py --- bake a per-case *hierarchical*
grid velocity module.

Companion to `build_grid_velocity_case.py` (uniform only).  This tool
handles **block-refined** Cartesian grids: a small list of uniform
Cartesian bricks, finest-first, sharing the same origin.  Every query
walks the block list in order and picks the first block containing the
query point.

The generated module registers itself as an
`AnalyticVelocityProvider`, so `run_tracking.py --velocity-source
analytic --velocity-module <module.py>` skips all mesh/octree code and
runs one hierarchical lookup per RK4 substage.

Runtime cost per substage: O(N_blocks) point-in-box tests + one O(1)
trilinear interpolation in the winning block.  For N_blocks <= 3 the
cost is essentially unchanged from the uniform-grid case.

Design choice for storage: each block's velocity is baked into a
single `.npz` file keyed by block index, alongside a small manifest
of block metadata (xmin, xmax, n_cells).  The generated `.py` module
loads the npz at import time and constructs JAX arrays.

Also emits a `.vtu` geometry file per block (hex cells, coloured by
|v|) so the grid can be visualised in ParaView.  Combine the blocks
with ParaView's "Group Datasets" filter, or open the multi-block
wrapper `.vtm` file we also emit.

Example (recirc_2026 4-lvl block-refined grid):

    python scripts/build_hier_grid_velocity_case.py \\
        --source analytic \\
        --source-module /scratch/shared/ROM/FOM_analytic/recirc_2026/recirculation_field.py \\
        --bbox   -0.0625 0.0625 -0.03125 0.03125 -0.015625 0.015625 \\
        --base-n 64 32 8 \\
        --grid-type 4lvl \\
        --refine-r1 0.03125 --refine-r2 0.015625 \\
        --out /scratch/shared/ROM/FOM_analytic/recirc_2026/grid_velocity_recirc_4lvl.py
"""

