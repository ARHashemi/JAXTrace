def sample_from_analytic(module_path: Path, points_xyz: np.ndarray) -> np.ndarray:
    import jax
    import jax.numpy as jnp
    spec = importlib.util.spec_from_file_location("_case", str(module_path))
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    vfn_v = jax.vmap(mod.velocity_fn)
    return np.asarray(vfn_v(jnp.asarray(points_xyz)))


def build_hct_projector(pvtu_path: Path, field_name: str = "Displacement",
                        cache_path: Path | None = None,
                        verbose: bool = True) -> dict:
    """Build (or load) the per-mesh HCT-3D state needed to evaluate
    the C1 Alfeld-split Bernstein cubic at arbitrary query points.

    Returns a dict with keys: `pts_mesh`, `conn`, `hct_coeffs`,
    `alfeld_centroids`, `ug` (a live vtkUnstructuredGrid for
    point-in-tet lookup via vtkCellLocator).

    If `cache_path` is given and exists, the SPR + HCT stage is
    loaded from the .npz there. If it does not exist, it is built
    and written. The mesh geometry and the case velocity are hashed
    into the cache filename so a mismatched cache is not silently
    reused.
    """
    reader = (vtk.vtkXMLPUnstructuredGridReader()
              if pvtu_path.suffix == ".pvtu"
              else vtk.vtkXMLUnstructuredGridReader())
    reader.SetFileName(str(pvtu_path)); reader.Update()
    ug = reader.GetOutput()

    pts_mesh = vtk_to_numpy(ug.GetPoints().GetData()).astype(np.float64)
    n_cells = ug.GetNumberOfCells()
    conn = np.empty((n_cells, 4), dtype=np.int64)
    cell = vtk.vtkGenericCell()
    for i in range(n_cells):
        ug.GetCell(i, cell)
        ids = cell.GetPointIds()
        for j in range(4):
            conn[i, j] = ids.GetId(j)
    v_nodal = vtk_to_numpy(
        ug.GetPointData().GetArray(field_name)).astype(np.float64)

    if cache_path is not None and cache_path.exists():
        if verbose:
            print(f"[hct-cache] loading {cache_path}")
        z = np.load(cache_path)
        hct_coeffs = z["hct_coeffs"]
        alfeld_centroids = z["alfeld_centroids"]
        # Sanity: cache must match this mesh + velocity.
        if (not np.array_equal(z["pts_mesh_hash"],
                               _hash_arr(pts_mesh))
                or not np.array_equal(z["v_nodal_hash"],
                                      _hash_arr(v_nodal))):
            raise SystemExit(f"[hct-cache] MISMATCH -- {cache_path} does "
                             f"not match this mesh + velocity. Delete "
                             f"the cache and rerun.")
    else:
        from jaxtrace.gpu.recovery.gradient_recovery import build_recovery
        from jaxtrace.gpu.recovery.hct3d import (
            build_alfeld_geometry, build_hct_bernstein_c1_taylor,
        )
        if verbose:
            print(f"[hct-cache] building SPR + Alfeld + HCT-3D coeffs "
                  f"for {n_cells:,} tets (this is the slow step)...")
        recovery = build_recovery(pts_mesh, conn, v_nodal,
                                  method="vertex_taylor", verbose=False)
        alfeld = build_alfeld_geometry(pts_mesh, conn, verbose=False)
        hct = build_hct_bernstein_c1_taylor(
            pts_mesh, conn, v_nodal,
            recovery.nodal_gradient,
            edge_grads=None,
            geom=alfeld, verbose=False,
        )
        hct_coeffs = hct.coeffs.astype(np.float32)
        alfeld_centroids = alfeld.centroids.astype(np.float64)
        if cache_path is not None:
            cache_path.parent.mkdir(parents=True, exist_ok=True)
            np.savez_compressed(
                cache_path,
                hct_coeffs=hct_coeffs,
                alfeld_centroids=alfeld_centroids,
                pts_mesh_hash=_hash_arr(pts_mesh),
                v_nodal_hash=_hash_arr(v_nodal),
            )
            if verbose:
                sz = cache_path.stat().st_size / (1024 * 1024)
                print(f"[hct-cache] wrote {cache_path} ({sz:.1f} MB)")

    return dict(pts_mesh=pts_mesh, conn=conn,
                hct_coeffs=hct_coeffs,
                alfeld_centroids=alfeld_centroids,
                ug=ug)


def _hash_arr(a: np.ndarray) -> np.ndarray:
    """Cheap fingerprint of an array (shape + first/last/mean bytes)."""
    import hashlib
    h = hashlib.sha1()
    h.update(np.asarray(a.shape, dtype=np.int64).tobytes())
    h.update(a.astype(np.float64, copy=False).tobytes())
    return np.frombuffer(h.digest(), dtype=np.uint8)


def sample_from_mesh(pvtu_path: Path, points_xyz: np.ndarray,
                     projection_method: str = "p1_raw",
                     field_name: str = "Displacement",
                     hct_state: dict | None = None) -> np.ndarray:
    """Project a mesh's nodal velocity field onto query points.

    projection_method:
        "p1_raw"    -- vtkProbeFilter (P1 barycentric interpolation).
                       Fast and, for FSW-style cases where the grid at
                       mesh's natural resolution or coarser, matches the
                       "grid vs mesh Slide 10" story where HCT is
                       demonstrably worse than P1 on refined grids.
                       DEFAULT.
        "hct_cubic" -- SPR nodal-gradient recovery + HCT-3D cubic
                       Bernstein reconstruction (Phase 3b Taylor-fit),
                       evaluated at query points via the Alfeld sub-tet
                       lookup used by scripts/analytic_grid_projection.py.
                       Kept for comparability; slower and (per Slide 10)
                       usually worse on grid centres.
    """
    reader = (vtk.vtkXMLPUnstructuredGridReader()
              if pvtu_path.suffix == ".pvtu"
              else vtk.vtkXMLUnstructuredGridReader())
    reader.SetFileName(str(pvtu_path)); reader.Update()
    ug = reader.GetOutput()

    if projection_method == "p1_raw":
        probe_pts = vtk.vtkPoints()
        probe_pts.SetData(numpy_to_vtk(points_xyz.astype(np.float64),
                                        deep=True))
        probe_poly = vtk.vtkPolyData(); probe_poly.SetPoints(probe_pts)
        probe = vtk.vtkProbeFilter()
        probe.SetInputData(probe_poly); probe.SetSourceData(ug); probe.Update()
        return vtk_to_numpy(
            probe.GetOutput().GetPointData().GetArray(field_name)
        ).astype(np.float64)

    if projection_method == "hct_cubic":
        from jaxtrace.gpu.recovery.hct3d import (
            ALFELD_SUBTET_PARENT_VERTS, bernstein_cubic_evaluate,
        )
        if hct_state is None:
            hct_state = build_hct_projector(pvtu_path, field_name=field_name,
                                             cache_path=None, verbose=True)
        pts_mesh = hct_state["pts_mesh"]
        conn = hct_state["conn"]
        hct_coeffs = hct_state["hct_coeffs"]
        alfeld_centroids = hct_state["alfeld_centroids"]
        ug_hct = hct_state["ug"]

        locator = vtk.vtkCellLocator()
        locator.SetDataSet(ug_hct); locator.BuildLocator()
        n_q = points_xyz.shape[0]
        v_out = np.zeros((n_q, 3), dtype=np.float64)
        cell = vtk.vtkGenericCell()
        pcoords = [0.0, 0.0, 0.0]
        weights_parent = [0.0, 0.0, 0.0, 0.0]
        for i in range(n_q):
            p = points_xyz[i]
            cid = locator.FindCell(p, 1e-6, cell, pcoords, weights_parent)
            if cid < 0:
                continue
            w_parent = np.asarray(weights_parent[:4], dtype=np.float64)
            s = int(np.argmin(w_parent))
            jkl = ALFELD_SUBTET_PARENT_VERTS[s]
            tet_nodes = conn[cid]
            v_j = pts_mesh[tet_nodes[jkl[0]]]
            v_k = pts_mesh[tet_nodes[jkl[1]]]
            v_l = pts_mesh[tet_nodes[jkl[2]]]
            v_c = alfeld_centroids[cid]
            M = np.column_stack([v_j - v_c, v_k - v_c, v_l - v_c])
            try:
                bjkl = np.linalg.solve(M, p - v_c)
            except np.linalg.LinAlgError:
                continue
            bvc = 1.0 - bjkl.sum()
            bary = np.array([bjkl[0], bjkl[1], bjkl[2], bvc],
                            dtype=np.float64)
            bary = np.maximum(bary, -1e-6)
            v_out[i] = bernstein_cubic_evaluate(hct_coeffs[cid, s], bary)
        return v_out

    raise ValueError(f"unknown projection_method: {projection_method}")


def cell_centres_of(block: dict) -> np.ndarray:
    xmin = block["xmin"]; xmax = block["xmax"]; nx, ny, nz = block["n_cells"]
    dx = (xmax - xmin) / np.array([nx, ny, nz], dtype=np.float64)
    xs = xmin[0] + (np.arange(nx) + 0.5) * dx[0]
    ys = xmin[1] + (np.arange(ny) + 0.5) * dx[1]
    zs = xmin[2] + (np.arange(nz) + 0.5) * dx[2]
    X, Y, Z = np.meshgrid(xs, ys, zs, indexing="ij")
    return np.column_stack([X.ravel(), Y.ravel(), Z.ravel()])


