def write_block_vtu(out_path: Path, block: dict, v_flat: np.ndarray,
                    block_index: int) -> None:
    """Write the block's hex-cell geometry as a VTU with per-cell |v|
    and full v-vector attached for ParaView colouring."""
    xmin = block["xmin"]; xmax = block["xmax"]; nx, ny, nz = block["n_cells"]
    dx = (xmax - xmin) / np.array([nx, ny, nz], dtype=np.float64)
    cxs = xmin[0] + np.arange(nx + 1) * dx[0]
    cys = xmin[1] + np.arange(ny + 1) * dx[1]
    czs = xmin[2] + np.arange(nz + 1) * dx[2]
    X, Y, Z = np.meshgrid(cxs, cys, czs, indexing="ij")
    pts = np.column_stack([X.ravel(), Y.ravel(), Z.ravel()])
    idx = lambda i, j, k: (i * (ny + 1) + j) * (nz + 1) + k
    n_cells = nx * ny * nz
    conn = np.empty((n_cells, 8), dtype=np.int64)
    c = 0
    for i in range(nx):
        for j in range(ny):
            for k in range(nz):
                conn[c, 0] = idx(i,     j,     k    )
                conn[c, 1] = idx(i + 1, j,     k    )
                conn[c, 2] = idx(i + 1, j + 1, k    )
                conn[c, 3] = idx(i,     j + 1, k    )
                conn[c, 4] = idx(i,     j,     k + 1)
                conn[c, 5] = idx(i + 1, j,     k + 1)
                conn[c, 6] = idx(i + 1, j + 1, k + 1)
                conn[c, 7] = idx(i,     j + 1, k + 1)
                c += 1

    ug = vtk.vtkUnstructuredGrid()
    vpts = vtk.vtkPoints()
    vpts.SetData(numpy_to_vtk(pts.astype(np.float64), deep=True))
    ug.SetPoints(vpts)
    id_arr = np.empty(9 * n_cells, dtype=np.int64)
    id_arr[0::9] = 8
    for kk in range(8):
        id_arr[kk + 1::9] = conn[:, kk]
    cell_arr = vtk.vtkCellArray()
    cell_arr.SetCells(n_cells, numpy_to_vtkIdTypeArray(id_arr, deep=True))
    cell_types = np.full(n_cells, vtk.VTK_HEXAHEDRON, dtype=np.uint8)
    ug.SetCells(numpy_to_vtk(cell_types, deep=True,
                              array_type=vtk.VTK_UNSIGNED_CHAR),
                cell_arr)
    v = v_flat.reshape(-1, 3).astype(np.float32)
    v_mag = np.linalg.norm(v, axis=1)
    varr = numpy_to_vtk(v, deep=True); varr.SetName("v"); varr.SetNumberOfComponents(3)
    marr = numpy_to_vtk(v_mag, deep=True); marr.SetName("v_mag")
    barr = numpy_to_vtk(np.full(n_cells, block_index, dtype=np.int32), deep=True)
    barr.SetName("block_index")
    ug.GetCellData().AddArray(varr)
    ug.GetCellData().AddArray(marr)
    ug.GetCellData().AddArray(barr)

    w = vtk.vtkXMLUnstructuredGridWriter()
    w.SetFileName(str(out_path))
    w.SetInputData(ug)
    w.SetDataModeToBinary()
    w.SetCompressorTypeToZLib()
    w.Write()


def write_vtm_wrapper(vtm_path: Path, per_block_paths: list[Path]) -> None:
    """Small multi-block wrapper so ParaView can open all blocks with one click."""
    body = "\n".join(
        f'    <DataSet index="{i}" file="{p.name}" name="block_{i}"/>'
        for i, p in enumerate(per_block_paths)
    )
    vtm_path.write_text(
        f'<?xml version="1.0"?>\n'
        f'<VTKFile type="vtkMultiBlockDataSet" version="1.0">\n'
        f'  <vtkMultiBlockDataSet>\n{body}\n  </vtkMultiBlockDataSet>\n'
        f'</VTKFile>\n'
    )


