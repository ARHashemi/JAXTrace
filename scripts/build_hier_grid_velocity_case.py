def make_malmo_aligned_hier_grid(source_pvtu: Path,
                                 bbox: tuple[float, ...],
                                 leaf_capacity: int = 256,
                                 max_depths: int | None = None,
                                 cells_per_edge: int = 1,
                                 verbose: bool = False) -> list[dict]:
    """Build a hierarchical grid aligned with the FOM's MALMO octree.

    Runs the same `build_global_morton_octree` used by the tracker on the
    source PVTU's mesh, then per-depth:
      * computes a bounding box that encloses all leaves at THAT depth
        (and everything finer -- since deeper leaves lie inside the
        coarser cube they refine, taking bbox of all leaves at depth
        >= d gives us the 'volume the mesh refines at least to level d')
      * sets grid cell size = MALMO cube edge / cells_per_edge.

    Returns finest-first list of block dicts.

    ``max_depths`` optionally caps how deep we go (e.g. 4 -> use only
    depths 2..4).  ``cells_per_edge = 1`` matches MALMO cube exactly.
    """
    # Load mesh
    reader = (vtk.vtkXMLPUnstructuredGridReader()
              if source_pvtu.suffix == ".pvtu"
              else vtk.vtkXMLUnstructuredGridReader())
    reader.SetFileName(str(source_pvtu)); reader.Update()
    ug = reader.GetOutput()
    pts_mesh = vtk_to_numpy(ug.GetPoints().GetData()).astype(np.float32)
    n_cells_mesh = ug.GetNumberOfCells()
    conn = np.empty((n_cells_mesh, 4), dtype=np.int32)
    cell = vtk.vtkGenericCell()
    for i in range(n_cells_mesh):
        ug.GetCell(i, cell); ids = cell.GetPointIds()
        for j in range(4): conn[i, j] = ids.GetId(j)

    # Compute centroids
    centroids = pts_mesh[conn].mean(axis=1)

    # Import MALMO builders lazily
    from jaxtrace.gpu.search.morton_octree_builder import (
        build_global_morton_octree, build_adaptive_octree_leaves,
    )
    ms = build_global_morton_octree(
        pts_mesh, conn, leaf_capacity=leaf_capacity, verbose=False,
    )
    leaves, _ = build_adaptive_octree_leaves(
        ms.morton_sorted,
        np.arange(ms.morton_sorted.size, dtype=np.int32),
        leaf_capacity=leaf_capacity,
    )
    per_depth: dict[int, list] = {}
    for lf in leaves:
        d = lf.prefix_bits // 3
        per_depth.setdefault(d, []).append(lf)
    depths_sorted = sorted(per_depth.keys())
    if verbose:
        print(f"  MALMO depths used: {depths_sorted}")

    # bbox from the CLI (should be mesh bbox with tiny epsilon)
    xmin_full = np.array([bbox[0], bbox[2], bbox[4]], dtype=np.float64)
    xmax_full = np.array([bbox[1], bbox[3], bbox[5]], dtype=np.float64)
    extent = ms.bbox_max.astype(np.float64) - ms.bbox_min.astype(np.float64)

    # For each depth d, we need the bounding box of the mesh region
    # that has at least that many refinement levels.  Since finer leaves
    # are always inside their coarser parent cube, "all cells at depth >= d"
    # is the right query.  We use the centroids of the leaves' member
    # elements to get the actual mesh region covered.
    blocks: list[dict] = []
    for d in depths_sorted:
        if max_depths is not None and d > max_depths:
            continue
        # collect all element ids in leaves at depth >= d
        elem_ids_here = []
        for lf in leaves:
            if lf.prefix_bits // 3 >= d:
                # these are element indices in morton_sorted order
                for idx in range(lf.start_idx, lf.start_idx + lf.length):
                    elem_ids_here.append(idx)
        elem_ids_here = np.asarray(elem_ids_here, dtype=np.int64)
        if elem_ids_here.size == 0:
            continue
        # actual element ids (unsorted)
        real_ids = np.arange(n_cells_mesh)[np.argsort(ms.morton_sorted)][elem_ids_here] \
            if hasattr(ms, "elem_ids_sorted") \
            else elem_ids_here
        # simpler + safer: use ms.elem_ids_sorted directly
        if hasattr(ms, "elem_ids_sorted"):
            real_ids = ms.elem_ids_sorted[elem_ids_here]
        # centroids of those elements
        cent = centroids[real_ids]
        cube_edge = extent / (2 ** d)
        # bbox = cent bbox +/- half a cube (to be safe about the leaf boundary)
        bmin = cent.min(axis=0) - 0.5 * cube_edge
        bmax = cent.max(axis=0) + 0.5 * cube_edge
        # clamp inside full mesh bbox
        bmin = np.maximum(bmin, xmin_full)
        bmax = np.minimum(bmax, xmax_full)
        # Compute per-axis n_cells so cell size ~ cube_edge / cells_per_edge
        target_dx = cube_edge / cells_per_edge
        n = np.maximum(2, np.round((bmax - bmin) / target_dx).astype(int))
        blocks.append(dict(xmin=bmin, xmax=bmax, n_cells=tuple(int(x) for x in n)))
        if verbose:
            n_cells_block = int(np.prod(n))
            print(f"    depth {d}: bbox x=[{bmin[0]:.3g},{bmax[0]:.3g}] "
                  f"y=[{bmin[1]:.3g},{bmax[1]:.3g}] "
                  f"z=[{bmin[2]:.3g},{bmax[2]:.3g}]  "
                  f"n={tuple(int(x) for x in n)}  cells={n_cells_block:,}")

    # Order finest-first: MALMO deepest depth = smallest cube = finest.
    blocks.reverse()
    return blocks


def make_hier_grid(bbox: tuple[float, ...],
                   base_n: tuple[int, int, int],
                   grid_type: str,
                   refine_r1: float,
                   refine_r2: float,
                   refine_r3: float = 0.0) -> list[dict]:
    """Return a finest-first list of block dicts (xmin, xmax, n_cells).

    grid_type ∈ {"uniform", "2lvl", "4lvl", "5lvl"}.  Refinement is
    always centred on the origin (matches recirc / rot_cyl / FSW
    cases).

    5lvl adds a third nested block for the 20-case cohort experiment:
      * base at (base_n)
      * inner1 at r <= refine_r1, 2 x base_n
      * inner2 at r <= refine_r2, 4 x base_n
      * inner3 at r <= refine_r3, 8 x base_n

    Intended for FSW where the pin-face shear-band at r ~= 21 mm
    drives PT error (Part 4 of the grid report), so users pick
    e.g. refine_r1=0.022, refine_r2=0.016, refine_r3=0.008.
    """
    xmin = np.array([bbox[0], bbox[2], bbox[4]], dtype=np.float64)
    xmax = np.array([bbox[1], bbox[3], bbox[5]], dtype=np.float64)
    base = dict(xmin=xmin.copy(), xmax=xmax.copy(),
                n_cells=tuple(base_n))
    if grid_type == "uniform":
        return [base]
    # 2-lvl: base + 2x-refined block within r ≤ refine_r1
    inner1 = dict(
        xmin=np.array([-refine_r1, -refine_r1, xmin[2]]),
        xmax=np.array([ refine_r1,  refine_r1, xmax[2]]),
        n_cells=(base_n[0] * 2, base_n[1] * 2, base_n[2] * 2),
    )
    if grid_type == "2lvl":
        return [inner1, base]
    # 4-lvl: base + 2x block + 4x block nested
    inner2 = dict(
        xmin=np.array([-refine_r2, -refine_r2, xmin[2]]),
        xmax=np.array([ refine_r2,  refine_r2, xmax[2]]),
        n_cells=(base_n[0] * 4, base_n[1] * 4, base_n[2] * 4),
    )
    if grid_type == "4lvl":
        return [inner2, inner1, base]
    # 5-lvl: base + 2x block + 3x block + 4x block nested.
    # The multipliers are capped at 4x (rather than the naive 8x) because
    # Part 4 of the grid report showed that refining past the underlying
    # finest tet edge (~140 um) gives no benefit under HCT.  4x base_n
    # = 360 xy cells at half-extent 8 mm gives Δx ~= 45 um.
    inner2b = dict(
        xmin=np.array([-refine_r2, -refine_r2, xmin[2]]),
        xmax=np.array([ refine_r2,  refine_r2, xmax[2]]),
        n_cells=(base_n[0] * 3, base_n[1] * 3, base_n[2] * 3),
    )
    inner3 = dict(
        xmin=np.array([-refine_r3, -refine_r3, xmin[2]]),
        xmax=np.array([ refine_r3,  refine_r3, xmax[2]]),
        n_cells=(base_n[0] * 4, base_n[1] * 4, base_n[2] * 4),
    )
    if grid_type == "5lvl":
        return [inner3, inner2b, inner1, base]
    raise ValueError(f"unknown grid_type: {grid_type}")


