def _fmt_block_summary(blocks: list[dict]) -> str:
    lines = []
    for i, b in enumerate(blocks):
        n = b["n_cells"]
        xmin, xmax = b["xmin"], b["xmax"]
        n_cells = int(np.prod(n))
        lines.append(f"        block {i}: n={n}, "
                     f"x=[{xmin[0]:g}, {xmax[0]:g}], "
                     f"y=[{xmin[1]:g}, {xmax[1]:g}], "
                     f"z=[{xmin[2]:g}, {xmax[2]:g}]  "
                     f"({n_cells:,} cells)")
    return "\n".join(lines)


def _fmt_block_meta(blocks: list[dict]) -> str:
    lines = []
    for b in blocks:
        xmin_tuple = tuple(float(v) for v in b["xmin"])
        xmax_tuple = tuple(float(v) for v in b["xmax"])
        n_tuple = tuple(int(v) for v in b["n_cells"])
        lines.append(f"    ({xmin_tuple!r}, {xmax_tuple!r}, {n_tuple!r}),")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", choices=["analytic", "mesh"], required=True)
    ap.add_argument("--source-module", type=Path)
    ap.add_argument("--source-pvtu", type=Path)
    ap.add_argument("--bbox", type=float, nargs=6, required=True,
                    metavar=("XMIN", "XMAX", "YMIN", "YMAX", "ZMIN", "ZMAX"))
    ap.add_argument("--base-n", type=int, nargs=3, required=True)
    ap.add_argument("--grid-type",
                    choices=["uniform", "2lvl", "4lvl", "5lvl", "malmo"],
                    required=True,
                    help="'uniform' | '2lvl' | '4lvl' as before, plus "
                         "'malmo' which extracts per-depth bboxes + "
                         "cube edges from the FOM's mesh-aligned Morton "
                         "octree (jaxtrace.gpu.search.morton_octree_builder). "
                         "Requires --source mesh.")
    ap.add_argument("--malmo-max-depth", type=int, default=None,
                    help="For --grid-type malmo: cap the deepest MALMO "
                         "depth used.  Default: all depths present in "
                         "the mesh's octree.")
    ap.add_argument("--malmo-cells-per-edge", type=int, default=1,
                    help="For --grid-type malmo: grid cell size = MALMO "
                         "cube edge / this factor.  1 (default) matches "
                         "MALMO exactly; 2 doubles the grid resolution "
                         "in every refined level.")
    ap.add_argument("--malmo-leaf-capacity", type=int, default=256,
                    help="For --grid-type malmo: leaf_capacity passed to "
                         "build_global_morton_octree.  Default 256 "
                         "matches the tracker.")
    ap.add_argument("--refine-r1", type=float, default=None,
                    help="Half-extent of the 2x-refined block (m). Required for 2lvl/4lvl.")
    ap.add_argument("--refine-r2", type=float, default=None,
                    help="Half-extent of the 4x-refined block (m). Required for 4lvl and 5lvl.")
    ap.add_argument("--refine-r3", type=float, default=None,
                    help="Half-extent of the 8x-refined block (m). Required for 5lvl.")
    ap.add_argument("--interp",
                    choices=["trilinear", "tricubic", "nearest"],
                    default="trilinear",
                    help="Per-block interpolation.  'trilinear' (C0, "
                         "default) matches the analytic-case runs. "
                         "'tricubic' uses Catmull-Rom cardinal cubic "
                         "(C1, 4x4x4 stencil per query, no gradient "
                         "input needed).  'nearest' is a diagnostic.")
    ap.add_argument("--mesh-projection", choices=["p1_raw", "hct_cubic"],
                    default="p1_raw",
                    help="Projection method used when --source mesh. "
                         "'p1_raw' (default) uses vtkProbeFilter (fast, "
                         "matches Slide 10 finding that HCT is worse on "
                         "grid centres). 'hct_cubic' runs SPR + Alfeld "
                         "Bernstein reconstruction (slower).")
    ap.add_argument("--hct-cache", type=Path, default=None,
                    help="Path to cache the per-case HCT-3D state "
                         "(SPR + Alfeld + Bernstein coeffs). Only used "
                         "when --mesh-projection hct_cubic. When set, "
                         "the first build for a case writes the cache; "
                         "subsequent builds for the same case reuse it "
                         "and skip SPR entirely. Recommend one cache "
                         "path per case dir.")
    ap.add_argument("--mesh-field", type=str, default="Displacement",
                    help="Name of the nodal field to project when "
                         "--source mesh. Default 'Displacement' matches "
                         "both the FSW FOM PVTUs and the analytic "
                         "recirc_2026/rot_cyl_2026 test cases.")
    ap.add_argument("--out", type=Path, required=True,
                    help="Path to the generated .py module.  A sibling "
                         "<stem>.npz stores per-block velocity, and "
                         "<stem>_geom_bK.vtu / <stem>_geom.vtm store "
                         "the ParaView geometry.")
    args = ap.parse_args()

    if args.grid_type in ("2lvl", "4lvl", "5lvl") and args.refine_r1 is None:
        raise SystemExit(f"--grid-type {args.grid_type} requires --refine-r1")
    if args.grid_type in ("4lvl", "5lvl") and args.refine_r2 is None:
        raise SystemExit(f"--grid-type {args.grid_type} requires --refine-r2")
    if args.grid_type == "5lvl" and args.refine_r3 is None:
        raise SystemExit("--grid-type 5lvl requires --refine-r3")

    if args.grid_type == "malmo":
        if args.source != "mesh":
            raise SystemExit("--grid-type malmo requires --source mesh "
                             "(needs the FOM PVTU to build the octree).")
        blocks = make_malmo_aligned_hier_grid(
            args.source_pvtu, tuple(args.bbox),
            leaf_capacity=args.malmo_leaf_capacity,
            max_depths=args.malmo_max_depth,
            cells_per_edge=args.malmo_cells_per_edge,
            verbose=True,
        )
    else:
        blocks = make_hier_grid(tuple(args.bbox), tuple(args.base_n),
                                args.grid_type,
                                args.refine_r1 or 0.0,
                                args.refine_r2 or 0.0,
                                args.refine_r3 or 0.0)
    print(f"[hier-grid] {args.grid_type}: {len(blocks)} block(s) "
          f"(finest first)")
    for i, b in enumerate(blocks):
        n = b["n_cells"]
        print(f"  block {i}: n={n}, x∈[{b['xmin'][0]:g},{b['xmax'][0]:g}], "
              f"cells={int(np.prod(n)):,}")

    # Pre-build the HCT projector once per invocation (loads cache if
    # present).  For p1_raw this is None and each per-block call just
    # runs vtkProbeFilter.
    hct_state = None
    if args.source == "mesh" and args.mesh_projection == "hct_cubic":
        hct_state = build_hct_projector(
            args.source_pvtu, field_name=args.mesh_field,
            cache_path=args.hct_cache, verbose=True)

    # Sample velocity per block at cell centres
    v_flat_per_block = []
    for i, b in enumerate(blocks):
        centres = cell_centres_of(b)
        if args.source == "analytic":
            v = sample_from_analytic(args.source_module, centres)
        else:
            v = sample_from_mesh(args.source_pvtu, centres,
                                 projection_method=args.mesh_projection,
                                 field_name=args.mesh_field,
                                 hct_state=hct_state)
        v_flat_per_block.append(v.astype(np.float32))
        print(f"    block {i}: sampled {centres.shape[0]:,} cell centres")

    # Write npz (keys v_0, v_1, ...)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    npz_path = args.out.with_suffix(".npz")
    np.savez_compressed(
        npz_path,
        **{f"v_{i}": v for i, v in enumerate(v_flat_per_block)},
    )
    print(f"[hier-grid] wrote {npz_path}")

    # Write per-block VTU geometry + a vtm wrapper
    per_block_vtu = []
    for i, (b, v) in enumerate(zip(blocks, v_flat_per_block)):
        vtu = args.out.parent / f"{args.out.stem}_geom_b{i}.vtu"
        write_block_vtu(vtu, b, v, block_index=i)
        per_block_vtu.append(vtu)
        print(f"[hier-grid] wrote {vtu.name}")
    vtm = args.out.parent / f"{args.out.stem}_geom.vtm"
    write_vtm_wrapper(vtm, per_block_vtu)
    print(f"[hier-grid] wrote {vtm.name}  (open in ParaView to see all blocks)")

    # Write the .py module
    src = TEMPLATE.format(
        case_label=args.out.stem,
        source_desc=(f"analytic:{args.source_module.name}"
                     if args.source == "analytic"
                     else f"mesh:{args.source_pvtu.name}"),
        n_blocks=len(blocks),
        block_summary_indented=_fmt_block_summary(blocks),
        block_meta_repr=_fmt_block_meta(blocks),
        interp=args.interp,
        npz_name=npz_path.name,
        velocity_dispatch=_make_velocity_dispatch(len(blocks)),
    )
    args.out.write_text(src)
    print(f"[hier-grid] wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
