def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True, type=Path,
                    help="folder containing the case families (READ-ONLY)")
    ap.add_argument("--out", type=Path, default=Path("."),
                    help="where to write the report (NOT under --root)")
    ap.add_argument("--quick", action="store_true",
                    help="structure + parameters only; no PVTU reads")
    ap.add_argument("--deep", action="store_true",
                    help="also open the last PVTU with VTK (slower, richer)")
    ap.add_argument("--max-depth", type=int, default=3)
    args = ap.parse_args()

    root = args.root.resolve()
    if not root.is_dir():
        print(f"ERROR: --root not found: {root}", file=sys.stderr)
        return 1

    out_dir = args.out.resolve()
    # Refuse to write inside the surveyed tree.
    if out_dir == root or str(out_dir).startswith(str(root) + os.sep):
        print(f"ERROR: --out is inside --root; the survey must not write there.",
              file=sys.stderr)
        return 1
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"surveying {root}")
    print(f"  mode: {'quick' if args.quick else ('deep' if args.deep else 'normal')}")
    t0 = time.time()

    cases = find_cases(root, args.max_depth)
    print(f"  found {len(cases)} .gid folders in {time.time()-t0:.1f}s")

    records = []
    for i, c in enumerate(cases, 1):
        t1 = time.time()
        rec = survey_case(c, args.quick, args.deep)
        records.append(rec)
        print(f"  [{i:3d}/{len(cases)}] {rec['family']}/{rec['case']:12s} "
              f"{rec.get('status','?'):14s} "
              f"pin={rec.get('pin_geometry','?'):12.12s} "
              f"tilt={rec.get('tilt_deg','?'):>5.5s} "
              f"n_pvtu={rec.get('n_pvtu',0):<5d} ({time.time()-t1:.1f}s)",
              flush=True)

    csv_path = out_dir / "case_survey.csv"
    with open(csv_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS, extrasaction="ignore")
        w.writeheader()
        for r in records:
            w.writerow(r)

    md_path = out_dir / "case_survey.md"
    write_markdown(md_path, root, records, args)

    print()
    print(f"  wrote {csv_path}")
    print(f"  wrote {md_path}")
    print(f"  total {time.time()-t0:.1f}s")
    return 0


def write_markdown(path: Path, root: Path, records: list, args) -> None:
    lines = [
        "# FSW case survey",
        "",
        f"Root: `{root}`  (read-only)",
        f"Generated: {time.strftime('%Y-%m-%d %H:%M')}  "
        f"· mode: {'quick' if args.quick else ('deep' if args.deep else 'normal')}",
        f"Cases found: **{len(records)}**",
        "",
    ]

    usable = [r for r in records if r.get("usable") == 1]
    if not args.quick:
        lines += [f"Usable (all four required fields present): "
                  f"**{len(usable)} / {len(records)}**", ""]

    # Group by family
    fams = {}
    for r in records:
        fams.setdefault(r["family"], []).append(r)

    lines += ["## By family", ""]
    for fam in sorted(fams):
        rs = fams[fam]
        lines += [f"### {fam}  ({len(rs)} cases)", ""]
        lines += ["| case | pin | tilt | ω signed | v (mm/min) | steps/rev | n_pvtu | last | status |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(rs, key=lambda x: x["case"]):
            lines.append(
                f"| `{r['case']}` | {r.get('pin_geometry','?')} | "
                f"{r.get('tilt_deg','?')} | {r.get('rotation_signed','?')} | "
                f"{r.get('advancing_mm_min','?')} | {r.get('steps_per_rev','?')} | "
                f"{r.get('n_pvtu',0)} | {r.get('last_step','?')} | "
                f"{r.get('status','?')} |"
            )
        lines.append("")

    # Things worth knowing before using any of these
    notes = []
    tilted = [r for r in records
              if _f(r.get("tilt_deg")) not in (None, 0.0)]
    if tilted:
        notes.append(
            f"**{len(tilted)} case(s) have a non-zero tilt angle** "
            f"({', '.join(r['case'] for r in tilted[:8])}"
            f"{'…' if len(tilted) > 8 else ''}). A tilted tool is NOT "
            "axisymmetric about the vertical, so its tool-frame field is "
            "periodic at ω, not steady — load a full revolution, not a single "
            "step."
        )
    ccw = [r for r in records if _f(r.get("rotation_signed")) and _f(r.get("rotation_signed")) > 0]
    if ccw:
        notes.append(
            f"**{len(ccw)} case(s) rotate counter-clockwise** (signed ω > 0): "
            f"{', '.join(r['case'] for r in ccw[:8])}"
            f"{'…' if len(ccw) > 8 else ''}. Their advancing side is mirrored; "
            "orientation must be detected per case, not assumed."
        )
    noncyl = [r for r in records
              if r.get("pin_geometry") and "CYLINDRIC" not in r["pin_geometry"].upper()]
    if noncyl:
        notes.append(
            f"**{len(noncyl)} case(s) have a non-cylindrical pin** "
            f"(threaded/fluted/flats/conical). These break axisymmetry, so the "
            "field is periodic at ω — load a full revolution."
        )
    mism = [r for r in records
            if (r.get("prefix_matches_folder") == 0 and r.get("file_prefix"))
            or r.get("copied_from")]
    if mism:
        pairs = []
        for r in mism[:8]:
            src = r.get("copied_from") or r.get("file_prefix")
            pairs.append(f"{r['case']}←{src}")
        notes.append(
            f"**{len(mism)} case(s) were COPIED from another case**, renamed and "
            f"re-run with changed parameters: {', '.join(pairs)}"
            f"{'…' if len(mism) > 8 else ''}. The inner files keep the source "
            "case's prefix (e.g. `D4.gid` holding `C2_*.pvtu`), but they are "
            "that case's own output and carry ITS parameters. Do not filter on "
            "the folder name, and read parameters from `data/*.som.dat`, not "
            "from a stale `.info`."
        )
    periodic = [r for r in records
                if (r.get("pin_geometry") and "CYLINDRIC" not in r["pin_geometry"].upper())
                or _f(r.get("som_tilt_deg")) not in (None, 0.0)]
    with_window = [r for r in periodic if r.get("vel_n_steps")]
    if with_window:
        ranges = sorted({f"{r.get('vel_start')}-{r.get('vel_end')}" for r in with_window})
        notes.append(
            f"**{len(with_window)} periodic case(s) declare a full-revolution "
            f"window** in their `run_jaxtrace.sh` (`VEL_START`..`VEL_END`): "
            f"{', '.join(ranges)}. Use that range for phase-resolved damage; a "
            "single last-step snapshot is one arbitrary rotational phase."
        )

    bad = [r for r in records if r.get("status") not in ("ok", "not-checked")]
    if bad:
        notes.append(
            f"**{len(bad)} case(s) are not directly usable**: "
            + ", ".join(f"`{r['case']}` ({r.get('status')})" for r in bad[:10])
            + ("…" if len(bad) > 10 else "")
        )

    if notes:
        lines += ["## Notes", ""] + [f"- {n}" for n in notes] + [""]

    lines += [
        "## Columns in `case_survey.csv`",
        "",
        "`status` — ok | missing-fields | no-post | no-pvtu | not-checked",
        "`usable` — all of " + ", ".join(f"`{f}`" for f in REQUIRED_FIELDS) + " present",
        "`healthy` — deep mode only: tetrahedral and no NaN/Inf",
        "",
    ]
    path.write_text("\n".join(lines))


def _f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


